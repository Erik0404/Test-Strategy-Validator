package org.thesis.TestStrategyGenerator;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.FileWriter;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.*;
import com.fasterxml.jackson.databind.DeserializationFeature;

public class TestStrategyGenerator {

    public static void main(String[] args) throws Exception {
        String jsonInput = Files.readString(Paths.get("src/main/resources/shot.json"));
    }

    public static void generateFromRawJson(String jsonInput, String refineryCode, List<Set<String>> extractedModels) throws Exception {
        ObjectMapper mapper = new ObjectMapper();
        mapper.configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
        StrategyData data = mapper.readValue(jsonInput, StrategyData.class);

        buildAndSaveMarkdown(data, extractedModels);
    }

    private static void buildAndSaveMarkdown(StrategyData data, List<Set<String>> extractedModels) throws Exception {
        StringBuilder md = new StringBuilder();
        md.append("# Test Strategy Sample\n\n");
        md.append("**Requirement:** ").append(data.requirement_text).append("\n\n");

        appendSection(md, "Conditions", data.conditions);
        appendSection(md, "Expectations", data.expectations);

        md.append("### Rules\n");
        for (Rule r : data.rules) {
            md.append("- ").append(r.logic).append(" => ").append(String.join(", ", r.result_ids)).append("\n");
        }
        md.append("\n");

        md.append("### Semantic Coverage\n");

        // Szemantikai mátrix generálása a kapott modellek alapján
        generateSemanticMatrix(md, data, extractedModels);

        try (FileWriter writer = new FileWriter("TestStrategy.md")) {
            writer.write(md.toString());
        }
        System.out.println("Markdown sikeresen generálva: TestStrategy.md");
    }

    private static void generateSemanticMatrix(StringBuilder md, StrategyData data, List<Set<String>> extractedModels) {
        if (extractedModels == null || extractedModels.isEmpty()) {
            md.append("*No valid models were generated by Refinery for this strategy.*\n");
            return;
        }

        List<String> cIds = data.conditions.stream().map(c -> c.id).toList();

        // Táblázat fejléce
        md.append("| Model ID | ").append(String.join(" | ", cIds)).append(" | Expected Outcomes | Coverage Status |\n");
        md.append("| --- |").append(" --- |".repeat(cIds.size() + 2)).append("\n");

        int coveredModelsCount = 0;

        for (int i = 0; i < extractedModels.size(); i++) {
            Set<String> currentModel = extractedModels.get(i);
            Map<String, Boolean> state = new HashMap<>();
            List<String> rowValues = new ArrayList<>();

            // Állapot kiértékelése (Mapping)
            for (Element condition : data.conditions) {
                // Benne van-e a condition 'source_text'-je a gráf tényei között?
                // TODO: kifinomultabb NLP/Regex mappingre cserélés
                boolean isConditionTrue = evaluateConditionInModel(condition, currentModel);
                state.put(condition.id, isConditionTrue);
                rowValues.add(isConditionTrue ? "True" : "False");
            }

            // Elvárások (Expected Outcomes) meghatározása a szabályok alapján
            Set<String> expectedIds = new TreeSet<>();
            for (Rule r : data.rules) {
                if (evaluateSimpleLogic(r.logic, state)) {
                    expectedIds.addAll(r.result_ids);
                }
            }

            // Elvárások ellenőrzése a modellben (Coverage Status)
            String coverageStatus = "-";
            if (!expectedIds.isEmpty()) {
                boolean isFullyCovered = verifyExpectationsInModel(expectedIds, data.expectations, currentModel);
                if (isFullyCovered) {
                    coverageStatus = "Covered";
                    coveredModelsCount++;
                } else {
                    coverageStatus = "Uncovered";
                }
            } else {
                coverageStatus = "N/A (No Rule Triggered)";
            }

            String expStr = expectedIds.isEmpty() ? "-" : String.join(" && ", expectedIds);

            // Táblázat sorának kiírása
            md.append("| Model-").append(i + 1)
                    .append(" | ").append(String.join(" | ", rowValues))
                    .append(" | ").append(expStr)
                    .append(" | ").append(coverageStatus).append(" |\n");
        }

        // Összegzés kiírása
        double coveragePercentage = (double) coveredModelsCount / extractedModels.size() * 100;
        md.append("\n**Semantic Coverage:** ").append(coveredModelsCount).append(" / ").append(extractedModels.size())
                .append(" models covered (").append(String.format("%.1f", coveragePercentage)).append("%)\n");
    }

    private static boolean evaluateConditionInModel(Element condition, Set<String> modelFacts) {
        String keyword = condition.source_text.trim();
        // Legegyszerűbb illesztés: ha a tények string reprezentációjában szerepel a kulcsszó
        return modelFacts.stream().anyMatch(fact -> fact.contains(keyword));
    }

    private static boolean verifyExpectationsInModel(Set<String> expectedIds, List<Element> expectations, Set<String> modelFacts) {
        for (String eId : expectedIds) {
            // Megkeressük az elvárás szövegét az azonosító alapján
            String expectedKeyword = expectations.stream()
                    .filter(e -> e.id.equals(eId))
                    .map(e -> e.source_text.trim())
                    .findFirst()
                    .orElse("");

            if (expectedKeyword.isEmpty()) return false;

            // Ha akár egy elvárás is hiányzik a gráfból, akkor az állapot nincs teljesen lefedve
            boolean factFound = modelFacts.stream().anyMatch(fact -> fact.contains(expectedKeyword));
            if (!factFound) {
                return false;
            }
        }
        return true;
    }

    private static boolean evaluateSimpleLogic(String logic, Map<String, Boolean> state) {
        String replaced = logic;
        for (Map.Entry<String, Boolean> entry : state.entrySet()) {
            replaced = replaced.replace(entry.getKey(), entry.getValue().toString());
        }
        return replaced.contains("true") && !replaced.contains("false") || replaced.equals("true");
    }

    private static void appendSection(StringBuilder md, String title, List<Element> elements) {
        if (elements == null || elements.isEmpty()){
            return;
        }
        md.append("### ").append(title).append("\n");
        for (Element e : elements) {
            md.append("- **").append(e.id).append("**: ").append(e.description)
                    .append(" *(Source: \"").append(e.source_text).append("\")*\n");
        }
        md.append("\n");
    }

    public static class StrategyData {
        public String requirement_text;
        public List<Element> conditions;
        public List<Element> expectations;
        public List<Rule> rules;
    }

    public static class Element {
        public String id, description, source_text;
    }

    public static class Rule {
        public String logic;
        public List<String> result_ids;
    }

}